"""Lists the platform tags and environment variables describing the interpreter running this script.

Platform tags are found using an internal pip function therefore pip must be
installed. Different versions of pip may produce different results. The output
is a generated Go file containing a slice of PEP425Tag structs as defined in
pypi.go and a map of variable names to string values.
"""
import datetime
import os
import platform
import sys

from pip._internal.models import target_python


def _header():
  """Generates some documentation for the go file.

  It includes the current date and time as well as some details about the Python
  interpreter we are running under.

  Returns:
    str: a few lines of Go comments.
  """
  template = ('// Code generated by gen.py; DO NOT EDIT.\n'
              '// This was generated at {date}.\n'
              '// Python implementation: {impl}.\n'
              '// Python-reported platform: {platform}.\n'
              '// Python version: {version}.\n')
  return template.format(
      date=datetime.datetime.now(datetime.timezone.utc).strftime('%a, %d %b %Y %H:%M:%S UTC'),
      impl=sys.implementation.name,
      platform=platform.platform(),
      version=sys.version.replace('\n', ' '))


def _format_full_version(info):
  """Formats a version number. Taken from PEP 508."""
  version = '{0.major}.{0.minor}.{0.micro}'.format(info)
  kind = info.releaselevel
  if kind != 'final':
    version += kind[0] + str(info.serial)
  return version


def main():
  """Print the supported tags to stdout."""
  print(_header())
  print('package internal')
  print()
  print('var PlatformTags = []PEP425Tag{')
  # Generate tags for the current Python interpreter as well as earlier Python 3.x minor versions
  # down to 3.7. This allows C-extension wheels (cp313, cp312, cp311, cp310, cp39, etc.) for packages
  # like tensorflow to match on the canonical platform when running under a newer Python version.
  seen = set()
  current_version = sys.version_info[:2]
  versions = [current_version]
  if current_version[0] == 3:
    versions += [(3, minor) for minor in range(current_version[1] - 1, 6, -1)]
  for ver in versions:
    target = target_python.TargetPython(py_version_info=ver)
    for tag in target.get_sorted_tags():
      key = (tag.interpreter, tag.abi, tag.platform)
      if key not in seen:
        seen.add(key)
        print('\t{')
        print('\t\tPython:   "{}",'.format(tag.interpreter))
        print('\t\tABI:      "{}",'.format(tag.abi))
        print('\t\tPlatform: "{}",'.format(tag.platform))
        print('\t},')
  print('}')
  print()
  # Now look up each of the environment markers as per PEP 508.
  # (https://www.python.org/dev/peps/pep-0508/#environment-markers)
  print('var Markers = map[string]string{')
  print('\t"os_name":                        "{}",'.format(os.name))
  print('\t"sys_platform":                   "{}",'.format(sys.platform))
  print('\t"platform_machine":               "{}",'.format(platform.machine()))
  print('\t"platform_python_implementation": "{}",'.format(platform.python_implementation()))
  print('\t"platform_release":               "{}",'.format(platform.release()))
  print('\t"platform_system":                "{}",'.format(platform.system()))
  print('\t"platform_version":               "{}",'.format(platform.version()))
  print('\t"python_version":                 "{}",'.format('.'.join(platform.python_version_tuple()[:2])))
  print('\t"python_full_version":            "{}",'.format(platform.python_version()))
  print('\t"implementation_name":            "{}",'.format(sys.implementation.name))
  if hasattr(sys, 'implementation'):
    implementation_version = _format_full_version(sys.implementation.version)
  else:
    implementation_version = "0"
  print('\t"implementation_version":         "{}",'.format(implementation_version))
  print('}')


if __name__ == '__main__':
  main()
